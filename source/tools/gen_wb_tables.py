# Wonderblue-OS: the fixed-point tables of its sound engine -> firmware/gen/wb_tables.h
#   WB_INC     phase step per sample (2^32 a cycle) of MIDI note 0..127 at 44.1 kHz
#   WB_SEMI    2^(s/12) for s = -48..48, Q16 (pitch offsets, swoops, the break's tune)
#   WB_TANH    tanh(x * 4) / tanh(4) over x = -1..1 in 257 steps, Q15 (drive, the drum bus, the limiter's knee)
#   WB_SVF     2 sin(pi fc / 44100) for fc on a log scale, 30 Hz .. 7 kHz in 128 steps, Q15 (the filters)
#   WB_SVF_HZ  those cutoffs in Hz
import math, pathlib
out = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "gen" / "wb_tables.h"
FS = 44100.0
def arr(name, ctype, vals, per=12):
    s = f"static const {ctype} {name}[{len(vals)}] = {{\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(v) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"
inc = [round(2**32 * 440 * 2 ** ((n - 69) / 12) / FS) for n in range(128)]
semi = [round(65536 * 2 ** (s / 12)) for s in range(-48, 49)]
th = [round(32767 * math.tanh((i / 128 - 1) * 4) / math.tanh(4)) for i in range(257)]
hz = [30 * (7000 / 30) ** (i / 127) for i in range(128)]
svf = [min(32000, round(32768 * 2 * math.sin(math.pi * f / FS))) for f in hz]
text = "/* generated by tools/gen_wb_tables.py: Wonderblue-OS's fixed-point tables, GPL-3.0-only */\n#pragma once\n#include <stdint.h>\n"
text += arr("WB_INC", "uint32_t", [i & 0xFFFFFFFF for i in inc], 8)
text += arr("WB_SEMI", "uint32_t", semi, 10)
text += arr("WB_TANH", "int16_t", th)
text += arr("WB_SVF", "uint16_t", svf)
text += arr("WB_SVF_HZ", "uint16_t", [round(h) for h in hz])
out.write_text(text)
print(out, len(text), "B")
